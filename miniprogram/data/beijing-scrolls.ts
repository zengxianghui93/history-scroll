interface LandmarkSection {
  title: string;
  text: string;
  illustration?: { src: string; alt: string; caption: string };
  aside?: { label: string; text: string };
  observations?: { name: string; detail: string }[];
  collapsed?: boolean;
  route?: [string, string, string];
  squarePlan?: boolean;
  link?: { label: string; path: string };
}

interface LandmarkStory {
  cover?: { src: string; alt: string; caption?: string };
  duration?: string;
  title: string;
  sections: LandmarkSection[];
}

export interface ScrollLandmark {
  id: string;
  name: string;
  takeaway: string;
  x: number;
  y: number;
  path: string;
  fengwuId?: string;
  story?: LandmarkStory;
}

export interface CityScroll {
  id: string;
  name: string;
  image: string;
  landmarks: ScrollLandmark[];
}

function story(id: string, name: string, x: number, y: number, takeaway: string, title: string, sections: LandmarkSection[], fengwuId?: string, duration?: string, cover?: LandmarkStory['cover']): ScrollLandmark {
  return { id, name, x, y, takeaway, path: '/pages/beijing-landmark/beijing-landmark?id=' + id, story: { title, sections, ...(duration ? { duration } : {}), ...(cover ? { cover } : {}) }, fengwuId };
}

function place(id: string, name: string, x: number, y: number, takeaway: string, fengwuId: string): ScrollLandmark {
  return { id, name, x, y, takeaway, path: beijingPlacePath(fengwuId), fengwuId };
}

