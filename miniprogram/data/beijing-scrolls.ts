export const scrollLandmarks: ScrollLandmark[] = beijingScrolls.flatMap((scroll: CityScroll): ScrollLandmark[] => scroll.landmarks);

export function landmarkIdForFengwu(id: string): string {
  return scrollLandmarks.find((entry: ScrollLandmark): boolean => entry.fengwuId === id)?.id ?? '';
}

export function findScrollLandmark(id: unknown): ScrollLandmark {
  const entry: ScrollLandmark | undefined = scrollLandmarks.find((landmark: ScrollLandmark): boolean => landmark.id === id);
  if (!entry) throw new RangeError('北京画卷地标不存在：' + String(id));
  return entry;
}

export function scrollIndexForLandmark(id: string): number {
  const index: number = beijingScrolls.findIndex((scroll: CityScroll): boolean => scroll.landmarks.some((entry: ScrollLandmark): boolean => entry.id === id));
  if (index < 0) throw new RangeError('北京画卷未收录地标：' + id);
  return index;
}
