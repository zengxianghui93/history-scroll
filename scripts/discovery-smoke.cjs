function createRuntime() {
  const storage = new Map();
  const modules = new Map();
  const navigation = [];
  const toasts = [];
  const redirects = [];
  const clipboard = [];
  const vibrations = [];
  const diagnostics = [];
  const scrolls = [];
  const currentPages = [];
  let mapStageBounds = { width: 340, height: 620 };
  let rejectedNavigation = false;
  let clockMs;
  const cloudHarness = createCloudHarness(() => clockMs ?? Date.now());
  const config = JSON.parse(fs.readFileSync(path.join(projectRoot, 'miniprogram/app.json'), 'utf8'));
  const registeredPages = [...config.pages, ...config.subpackages.flatMap(({ root, pages }) => pages.map((page) => root + '/' + page))];
  const tabRoutes = config.tabBar.list.map((item) => '/' + item.pagePath);
  const app = { globalData: { pet: null, cities: [], chapters: [] } };
  let definition;
  let componentDefinition;
  const context = vm.createContext({
    Date: class extends Date {
      static now() { return clockMs ?? Date.now(); }
    },
    wx: {
      cloud: { init: () => {}, callFunction: cloudHarness.invoke },
      removeStorageSync: (key) => storage.delete(key),
      getStorageInfoSync: () => ({ keys: [...storage.keys()] }),
      getStorageSync: (key) => storage.has(key) ? structuredClone(storage.get(key)) : '',
      setStorageSync: (key, value) => storage.set(key, structuredClone(value)),
      showToast: (options) => toasts.push(structuredClone(options)),
      navigateTo: ({ url, success, fail }) => {
        assert.ok(!tabRoutes.includes(url.split('?')[0]), '普通跳转不能打开 Tab：' + url);
        if (rejectedNavigation) {
          rejectedNavigation = false;
          fail({ errMsg: 'navigateTo:fail page limit' });
          return;
        }
        navigation.push(url);
        if (success) success();
      },
      switchTab: ({ url }) => {
        assert.ok(tabRoutes.includes(url), 'switchTab 仅接收已注册的 Tab 路径：' + url);
        navigation.push(url);
      },
      showActionSheet: ({ itemList, success }) => {
        assert.equal(itemList.length, 1, '北京与西安可互相切换');
        success({ tapIndex: 0 });
      },
      setClipboardData: ({ data }) => clipboard.push(data),
      canIUse: (feature) => feature === 'vibrateShort',
      vibrateShort: ({ type }) => vibrations.push(type),
      setNavigationBarTitle: () => {},
      createSelectorQuery: () => {
        const selectors = [];
        return {
          select: (selector) => ({ boundingClientRect: () => selectors.push(selector) }),
          exec: (callback) => {
            assert.deepEqual(selectors, ['.map-stage', '.map-dots']);
            callback([mapStageBounds, { height: 28 }]);
          },
        };
      },
      pageScrollTo: (options) => scrolls.push(structuredClone(options)),
      reLaunch: ({ url }) => navigation.push(url),
      redirectTo: ({ url }) => {
        assert.ok(!tabRoutes.includes(url.split('?')[0]), '替换页面不能打开 Tab：' + url);
        navigation.push(url);
        redirects.push(url);
      },
      navigateBack: ({ delta }) => navigation.push('back:' + delta),
    },
    console: { ...console, warn: (...fields) => diagnostics.push(fields), error: (...fields) => diagnostics.push(fields) }, setTimeout, clearTimeout,
    Page: (options) => { definition = options; },
    Component: (options) => { componentDefinition = options; },
    getApp: () => app,
    getCurrentPages: () => currentPages,
  });

  function loadModule(filename) {
    const resolved = path.resolve(filename);
    if (modules.has(resolved)) return modules.get(resolved).exports;
    const compiled = ts.transpileModule(fs.readFileSync(resolved, 'utf8'), {
      compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
      fileName: resolved,
    }).outputText;
    const mod = { exports: {} };
    modules.set(resolved, mod);
    const evaluate = vm.runInContext('(function(require, module, exports) {' + compiled + '\n})', context, { filename: resolved });
    evaluate((request) => loadModule(path.resolve(path.dirname(resolved), request + '.ts')), mod, mod.exports);
    return mod.exports;
  }

  function openPage(relative, options) {
    const route = relative.startsWith('xian/') || relative.startsWith('account/') || relative.startsWith('memories/') ? relative : 'pages/' + relative;
    assert.ok(registeredPages.includes(route), '只能打开 app.json 中注册的页面：' + relative);
    const filename = path.join(projectRoot, 'miniprogram', route + '.ts');
    modules.delete(filename);
    loadModule(filename);
    const page = { ...definition, route, data: structuredClone(definition.data ?? {}) };
    currentPages.push({ route, options });
    page.setData = (update) => Object.assign(page.data, structuredClone(update));
    if (page.onLoad) page.onLoad(options);
    if (page.onShow) page.onShow();
    if (page.onReady) page.onReady();
    return page;
  }

  function openComponent(relative, name, properties) {
    const route = relative.startsWith('xian/') || relative.startsWith('account/') || relative.startsWith('memories/') ? relative : 'pages/' + relative;
    const pageConfig = JSON.parse(fs.readFileSync(path.join(projectRoot, 'miniprogram', route + '.json'), 'utf8'));
    const componentPath = pageConfig.usingComponents[name];
    assert.ok(componentPath, '页面已注册组件：' + name);
    const filename = path.join(projectRoot, 'miniprogram', componentPath + '.ts');
    modules.delete(filename);
    loadModule(filename);
    const defaults = Object.fromEntries(Object.entries(componentDefinition.properties ?? {}).map(([key, value]) => [key, value.value]));
    const component = { ...componentDefinition.methods, data: structuredClone(componentDefinition.data), properties: { ...defaults, ...properties } };
    component.setData = (update) => Object.assign(component.data, structuredClone(update));
    componentDefinition.pageLifetimes?.show?.call(component);
    return component;
  }

  app.globalData.cities = loadModule(path.join(projectRoot, 'miniprogram/data/cities.ts')).default;
  app.globalData.chapters = loadModule(path.join(projectRoot, 'miniprogram/data/chapters.ts')).default;
  const account = () => loadModule(path.join(projectRoot, 'miniprogram/services/cloud-account.ts'));
  return { diagnostics, cloudHarness, login: () => account().loginCloud(), refresh: () => account().refreshCloud(), account, storage, app, navigation, toasts, redirects, clipboard, vibrations, scrolls, openPage, openComponent, loadModule,
    setClock: (time) => { clockMs = time; },
    advanceDay: () => { clockMs = (clockMs ?? Date.now()) + 86400000; },
    setMapStageBounds: (bounds) => { mapStageBounds = bounds; },
    rejectNextNavigation: () => { rejectedNavigation = true; } };
}

